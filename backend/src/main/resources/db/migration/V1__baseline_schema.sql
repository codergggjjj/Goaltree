CREATE TABLE users (
    id VARCHAR(36) PRIMARY KEY,
    email VARCHAR(191) NOT NULL UNIQUE,
    display_name VARCHAR(80) NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
    week_starts_on TINYINT NOT NULL DEFAULT 1,
    default_weekly_capacity_minutes INT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT chk_users_week_start CHECK (week_starts_on IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE goals (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    parent_id VARCHAR(36) NULL,
    title VARCHAR(80) NOT NULL,
    description TEXT NULL,
    start_date DATE NOT NULL,
    target_date DATE NOT NULL,
    priority VARCHAR(16) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    progress_mode VARCHAR(32) NOT NULL DEFAULT 'MILESTONE_WEIGHTED',
    current_progress DECIMAL(6,2) NOT NULL DEFAULT 0,
    metric_name VARCHAR(80) NULL,
    metric_unit VARCHAR(32) NULL,
    metric_start_value DECIMAL(18,4) NULL,
    metric_target_value DECIMAL(18,4) NULL,
    metric_current_value DECIMAL(18,4) NULL,
    version INT NOT NULL DEFAULT 1,
    paused_at DATETIME(3) NULL,
    completed_at DATETIME(3) NULL,
    archived_at DATETIME(3) NULL,
    deleted_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_goals_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_goals_parent FOREIGN KEY (parent_id) REFERENCES goals(id),
    CONSTRAINT chk_goals_dates CHECK (target_date > start_date),
    CONSTRAINT chk_goals_progress CHECK (current_progress BETWEEN 0 AND 100),
    INDEX idx_goals_user_status (user_id, status),
    INDEX idx_goals_parent (parent_id),
    INDEX idx_goals_target_date (target_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE completion_criteria (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    goal_id VARCHAR(36) NOT NULL,
    criterion_type VARCHAR(20) NOT NULL,
    description VARCHAR(500) NOT NULL,
    target_value DECIMAL(18,4) NULL,
    unit VARCHAR(32) NULL,
    required_flag BOOLEAN NOT NULL DEFAULT TRUE,
    satisfied BOOLEAN NOT NULL DEFAULT FALSE,
    satisfied_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_criteria_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_criteria_goal FOREIGN KEY (goal_id) REFERENCES goals(id),
    INDEX idx_criteria_goal (goal_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE milestones (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    goal_id VARCHAR(36) NOT NULL,
    title VARCHAR(120) NOT NULL,
    acceptance TEXT NOT NULL,
    target_date DATE NOT NULL,
    weight DECIMAL(6,2) NOT NULL,
    progress DECIMAL(6,2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',
    completed_at DATETIME(3) NULL,
    sort_order INT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 1,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_milestones_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_milestones_goal FOREIGN KEY (goal_id) REFERENCES goals(id),
    CONSTRAINT chk_milestones_weight CHECK (weight BETWEEN 0 AND 100),
    CONSTRAINT chk_milestones_progress CHECK (progress BETWEEN 0 AND 100),
    INDEX idx_milestones_goal_sort (goal_id, sort_order),
    INDEX idx_milestones_target_date (target_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE period_plans (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    plan_type VARCHAR(10) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    revision_no INT NOT NULL DEFAULT 1,
    supersedes_id VARCHAR(36) NULL,
    capacity_minutes INT NULL,
    summary TEXT NULL,
    confirmed_at DATETIME(3) NULL,
    effective_at DATETIME(3) NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_plans_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_plans_supersedes FOREIGN KEY (supersedes_id) REFERENCES period_plans(id),
    CONSTRAINT uq_plans_revision UNIQUE (user_id, plan_type, start_date, revision_no),
    CONSTRAINT chk_plans_dates CHECK (end_date >= start_date),
    INDEX idx_plans_effective (user_id, plan_type, start_date, end_date, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE plan_items (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    plan_id VARCHAR(36) NOT NULL,
    goal_id VARCHAR(36) NOT NULL,
    milestone_id VARCHAR(36) NULL,
    source_plan_item_id VARCHAR(36) NULL,
    expected_result VARCHAR(500) NOT NULL,
    planned_delta DECIMAL(6,2) NOT NULL,
    planned_effort_minutes INT NULL,
    notes TEXT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED',
    sort_order INT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_plan_items_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_plan_items_plan FOREIGN KEY (plan_id) REFERENCES period_plans(id),
    CONSTRAINT fk_plan_items_goal FOREIGN KEY (goal_id) REFERENCES goals(id),
    CONSTRAINT fk_plan_items_milestone FOREIGN KEY (milestone_id) REFERENCES milestones(id),
    CONSTRAINT fk_plan_items_source FOREIGN KEY (source_plan_item_id) REFERENCES plan_items(id),
    INDEX idx_plan_items_plan_sort (plan_id, sort_order),
    INDEX idx_plan_items_goal (goal_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE progress_entries (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    goal_id VARCHAR(36) NOT NULL,
    plan_item_id VARCHAR(36) NULL,
    milestone_id VARCHAR(36) NULL,
    occurred_at DATETIME(3) NOT NULL,
    result TEXT NOT NULL,
    delta_value DECIMAL(8,2) NULL,
    metric_value DECIMAL(18,4) NULL,
    effort_minutes INT NULL,
    blocker TEXT NULL,
    blocker_active BOOLEAN NOT NULL DEFAULT FALSE,
    evidence_text TEXT NULL,
    evidence_url VARCHAR(1000) NULL,
    correction_of_id VARCHAR(36) NULL,
    revision_no INT NOT NULL DEFAULT 1,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_progress_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_progress_goal FOREIGN KEY (goal_id) REFERENCES goals(id),
    CONSTRAINT fk_progress_plan_item FOREIGN KEY (plan_item_id) REFERENCES plan_items(id),
    CONSTRAINT fk_progress_milestone FOREIGN KEY (milestone_id) REFERENCES milestones(id),
    CONSTRAINT fk_progress_correction FOREIGN KEY (correction_of_id) REFERENCES progress_entries(id),
    INDEX idx_progress_goal_time (goal_id, occurred_at),
    INDEX idx_progress_user_time (user_id, occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE weekly_reviews (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    week_start DATE NOT NULL,
    week_end DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    capacity_assessment TEXT NULL,
    summary TEXT NULL,
    snapshot_json JSON NULL,
    submitted_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uq_reviews_week UNIQUE (user_id, week_start),
    CONSTRAINT chk_reviews_dates CHECK (week_end >= week_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE review_goal_items (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    review_id VARCHAR(36) NOT NULL,
    goal_id VARCHAR(36) NOT NULL,
    planned_delta DECIMAL(8,2) NOT NULL,
    actual_delta DECIMAL(8,2) NOT NULL,
    deviation DECIMAL(8,2) NOT NULL,
    cause VARCHAR(20) NULL,
    confidence TINYINT NULL,
    health VARCHAR(24) NULL,
    decision_code VARCHAR(20) NULL,
    insight TEXT NULL,
    conclusion TEXT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_review_items_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_review_items_review FOREIGN KEY (review_id) REFERENCES weekly_reviews(id),
    CONSTRAINT fk_review_items_goal FOREIGN KEY (goal_id) REFERENCES goals(id),
    CONSTRAINT uq_review_items_goal UNIQUE (review_id, goal_id),
    CONSTRAINT chk_review_items_confidence CHECK (confidence IS NULL OR confidence BETWEEN 1 AND 5),
    INDEX idx_review_items_goal (goal_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE adjustments (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    review_id VARCHAR(36) NULL,
    reason TEXT NOT NULL,
    effective_date DATE NOT NULL,
    scope_code VARCHAR(100) NOT NULL,
    before_snapshot JSON NOT NULL,
    after_snapshot JSON NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_adjustments_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_adjustments_review FOREIGN KEY (review_id) REFERENCES weekly_reviews(id),
    INDEX idx_adjustments_effective (user_id, effective_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE revisions (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    adjustment_id VARCHAR(36) NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id VARCHAR(36) NOT NULL,
    revision_no INT NOT NULL,
    action_code VARCHAR(24) NOT NULL,
    reason TEXT NULL,
    effective_at DATETIME(3) NOT NULL,
    before_json JSON NULL,
    after_json JSON NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_revisions_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_revisions_adjustment FOREIGN KEY (adjustment_id) REFERENCES adjustments(id),
    CONSTRAINT uq_revisions_entity UNIQUE (entity_type, entity_id, revision_no),
    INDEX idx_revisions_lookup (user_id, entity_type, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE idempotency_keys (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    status_code INT NOT NULL,
    response_json JSON NOT NULL,
    expires_at DATETIME(3) NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_idempotency_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uq_idempotency_key UNIQUE (user_id, idempotency_key),
    INDEX idx_idempotency_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
